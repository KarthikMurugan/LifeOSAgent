const {chromium}=await import(process.env.DAYGLOW_PLAYWRIGHT || 'playwright');
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
const base=process.env.DAYGLOW_TEST_URL || 'http://127.0.0.1:8000';
const screenshots=process.env.DAYGLOW_SCREENSHOT_DIR || 'screenshots';
await mkdir(screenshots,{recursive:true});
const browser = await chromium.launch({headless:true,channel:process.env.DAYGLOW_BROWSER_CHANNEL || 'chrome'});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
await page.goto(base);
await page.waitForSelector('#work-tasks .task',{state:'attached'});
assert.equal(await page.locator('#work-tasks .task').count(),4);
assert.equal(await page.locator('#home-tasks .task').count(),3);
assert.equal(await page.locator('#workspace-panels').isVisible(),false);
const response=page.waitForResponse(r=>r.url().endsWith('/api/agent/plan')&&r.request().method()==='POST',{timeout:300000});
await page.locator('#plan').click();
const result=(await (await response).json()).plan;
assert.equal(result.blocks.length,7);
await page.waitForFunction(()=>document.querySelector('#plan').textContent.includes('Replan'));
assert.equal(await page.locator('body').getAttribute('data-view'),'all');
assert.equal(await page.locator('#workspace-panels').isVisible(),true);
assert.equal(await page.locator('.calendar').isVisible(),true);
assert.equal(await page.locator('.task-grid').isVisible(),false);
assert.equal(await page.locator('.right-column').isVisible(),false);
assert.ok((await page.locator('#today-summary').textContent()).includes('7 tasks planned'));
await page.screenshot({path:screenshots+'/dayglow-today-planned.png',fullPage:true,animations:'disabled'});
await page.locator('button[data-view="calendar"]').click();
assert.equal(await page.locator('#schedule .slot').count(),11);
await page.screenshot({path:screenshots+'/dayglow-calendar.png',fullPage:true});
await page.locator('button[data-view="work"]').click();
await page.locator('input[data-id="w1"]').check();
await page.locator('button[data-view="all"]').click();
await page.route('**/api/agent/plan',async route=>{
 await new Promise(resolve=>setTimeout(resolve,400));
 await route.continue();
});
const replan=page.waitForResponse(r=>r.url().endsWith('/api/agent/plan')&&r.request().method()==='POST',{timeout:300000});
await page.locator('#plan').click();
assert.equal(await page.locator('.calendar').isVisible(),true);
assert.equal(await page.locator('#schedule .slot').count(),11);
const second=(await (await replan).json()).plan;
assert.equal(second.blocks.length,6);assert.equal(second.run_count,2);
assert.ok(!second.blocks.some(b=>b.id==='w1'));
await page.waitForFunction(()=>!document.querySelector('#plan').disabled);
await page.unroute('**/api/agent/plan');
await page.reload();
await page.waitForFunction(()=>document.querySelector('#plan').textContent.includes('Replan'));
assert.equal(await page.locator('input[data-id="w1"]').isChecked(),true);
assert.equal(await page.locator('#schedule .slot').count(),10);
assert.equal(await page.locator('.calendar').isVisible(),true);
assert.ok((await page.locator('#today-summary').textContent()).includes('6 tasks planned'));
await page.locator('button[data-view="copilot"]').click();
assert.equal(await page.locator('#activity .activity-item').count(),5);
let planningRequests=0;
page.on('request',request=>{if(request.url().endsWith('/api/agent/plan'))planningRequests++});
const followup=page.waitForResponse(r=>r.url().endsWith('/api/chat'),{timeout:300000});
await page.locator('#prompt').fill('What time did you schedule groceries?');
await page.locator('#chat button').click();
const chatResult=await (await followup).json();
assert.equal(chatResult.plan,null);
await page.waitForFunction(()=>!document.querySelector('#plan').disabled);
assert.equal(planningRequests,0); // "schedule" in a follow-up must not trigger replanning.
assert.ok((await page.locator('.message.bot').last().textContent()).includes(chatResult.reply));
const chatPlanResponse=page.waitForResponse(r=>r.url().endsWith('/api/chat'),{timeout:300000});
await page.locator('#prompt').fill('Replan my day');
await page.locator('#chat button').click();
const chatPlan=await (await chatPlanResponse).json();
assert.equal(chatPlan.plan.blocks.length,6);
assert.equal(chatPlan.plan.run_count,3);
await page.waitForFunction(()=>!document.querySelector('#plan').disabled);
assert.equal(await page.locator('#schedule .slot').count(),10);
assert.equal(await page.locator('#activity .activity-item').count(),5);
// Waiting on the model locks input and task changes; user text remains plain text.
await page.route('**/api/chat',async route=>{
 await new Promise(resolve=>setTimeout(resolve,400));
 await route.fulfill({json:{reply:'<b>Use the existing plan</b>',plan:null}});
});
await page.locator('#prompt').fill('Explain the plan');
await page.locator('#chat button').click();
assert.equal(await page.locator('#plan').isDisabled(),true);
assert.equal(await page.locator('#prompt').isDisabled(),true);
assert.equal(await page.locator('input[data-id="w1"]').isDisabled(),true);
await page.waitForFunction(()=>!document.querySelector('#plan').disabled);
assert.ok((await page.locator('.message.bot').last().textContent()).includes('<b>Use the existing plan</b>'));
assert.equal(await page.locator('.message.bot').last().locator('b').count(),0);
await page.unroute('**/api/chat');
await page.route('**/api/chat',route=>route.fulfill({status:502,body:'Unavailable'}));
await page.locator('#prompt').fill('Help me');
await page.locator('#chat button').click();
await page.waitForFunction(()=>[...document.querySelectorAll('.message.bot')].some(e=>e.textContent.includes('Unable to reach your copilot')));
assert.equal(await page.locator('#prompt').isEnabled(),true);
await page.unroute('**/api/chat');
// UI error path: failed service request must restore the button and show feedback.
await page.route('**/api/agent/plan',route=>route.fulfill({status:503,body:'Unavailable'}));
await page.locator('#plan').click();
await page.waitForFunction(()=>[...document.querySelectorAll('.message.bot')].some(e=>e.textContent.includes('Unable to plan')));
assert.equal(await page.locator('#plan').isEnabled(),true);
await page.locator('button[data-view="all"]').click();
assert.equal(await page.locator('#schedule .slot').count(),10);
assert.equal(await page.locator('.calendar').isVisible(),true);
await page.unroute('**/api/agent/plan');
await page.waitForFunction(()=>!document.querySelector('#toast').classList.contains('show'));
await page.locator('button[data-view="all"]').click();
await page.screenshot({path:screenshots+'/dayglow-today.png',fullPage:true,animations:'disabled'});
const mobile=await browser.newPage({viewport:{width:390,height:844}});
await mobile.goto(base);
await mobile.waitForFunction(()=>document.querySelector('#plan').disabled===false);
await mobile.screenshot({path:screenshots+'/dayglow-mobile.png',fullPage:false,animations:'disabled'});
assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
await mobile.locator('#plan').click();
await mobile.waitForFunction(()=>document.body.dataset.planned==='true');
assert.equal(await mobile.locator('.calendar').isVisible(),true);
assert.equal(await mobile.locator('#schedule .slot').count(),11);
assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
await mobile.screenshot({path:screenshots+'/dayglow-mobile-planned.png',fullPage:true,animations:'disabled'});
assert.deepEqual(errors,[]);
await browser.close();
console.log('Browser workflow passed: plan, calendar, complete task, replan, activity, chat, error recovery, reload restoration, mobile layout.');
